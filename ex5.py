# Ler 3 valores e achar a média aritmetica e no final mostrar o resultado da média
print("Bem Vindo - Ao calculador de média aritmetica! ")
a=float(input("digite o primeiro valor "))
b=float(input("digite o segundo valor "))
c=float(input("digite o terceiro valor "))
resultado= float((a+b+c)/(3))
print(f"Sua média é: {resultado:.2f}")





